    /** 去掉行政区后缀，便于「厦门市」「云南省」「广西壮族自治区」这类写法也能命中 */
    private fun normalize(raw: String): String {
        var s = raw.trim()
        listOf(
            "特别行政区", "自治区", "自治州", "地区", "省", "市", "县", "区"
        ).forEach { suffix ->
            if (s.length > suffix.length && s.endsWith(suffix)) s = s.dropLast(suffix.length)
        }
        // 「广西壮族」「新疆维吾尔」这类带民族名的写法，取前两个字再试
        return s
    }

    /**
     * 从一句话里认出城市名（取最长命中），认不出返回 null。
     * 给 AI 联网搜索用：问「重庆有什么小众景点」时要把「重庆」当城市限定传给高德，
     * 否则全国范围搜「小众景点」会返回一堆无关城市的结果。
     */
    fun detectIn(text: String): String? {
        if (text.isBlank()) return null
        return table.keys
            .filter { text.contains(it) }
            .maxByOrNull { it.length }
    }

    /**
     * 城市名 → (lon, lat)。命中不了返回 null，调用方应保持「未选坐标」而不是猜一个位置。
     */
    fun lonLat(raw: String): Pair<Double, Double>? {
        val name = raw.trim()
        if (name.isEmpty()) return null
        table[name]?.let { return it }
        val n = normalize(name)
        table[n]?.let { return it }
        // 「大理白族自治州」「西双版纳傣族自治州」：按前缀匹配表里的短名
        return table.entries
            .filter { n.startsWith(it.key) || it.key.startsWith(n) }
            .maxByOrNull { it.key.length }
            ?.value
    }
